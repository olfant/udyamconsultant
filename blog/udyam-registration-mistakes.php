            can be a proprietorship, partnership, company, LLP, cooperative
            society, trust, or another eligible structure. Choosing the right
            one matters a lot. It affects how the business is run, how taxes
            are paid, and how much personal liability each owner has. Getting
            it wrong can lead to problems down the road. It's important to think
            about what fits best.
        </p>

        <p class="mb-0">
