    <div class="content">
        <p>
            Udyam registration is not a yearly registration that needs to be renewed
            like a licence. The official Udyam portal states that there is no need
            for renewal of registration.
        </p>

        <p>
            However, this does not mean that an MSME can ignore its information
            permanently. Enterprises may need to update relevant information when
            required, particularly information affecting classification.
        </p>

        <p class="mb-0">
