    <div class="content">
        <p>
            MSME classification is based on investment in plant and machinery or
            equipment and annual turnover. The rules for classifying businesses were
            changed. These changes start on April 1, 2025.<br>
            Now, a very small business can have an investment of up to 2.5 crore and
            a sales amount of up to 10 crore. For a business, the limits are 25 crore
            in investment and 100 crore in sales.
        </p>

        <p class="mb-0">
            Since these figures are connected with government records, businesses
            should maintain accurate financial and tax information.
        </p>
    </div>
</div>

